def cmd_setup(args, cfg) -> None:
    """Write config/league.toml without an interactive prompt.

    Agent-safe: every value comes from a flag, nothing blocks on stdin.
    """
    path = pathlib.Path(args.config)
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = load_config(path)
    league = existing.get("league", {}) or {}
    league["provider"] = args.provider or league.get("provider", "espn")
    if args.league:
        league["league_id"] = str(args.league)
    if args.teams:
        league["teams"] = args.teams
    league.setdefault("league_id", "")
    league.setdefault("teams", 10)
    league.setdefault("name", "")

    roster = existing.get("roster") or {
        "QB": 1, "RB": 2, "WR": 2, "TE": 1, "FLEX": 1, "K": 1, "DEF": 1,
        "bench": 6, "flex_eligible": ["RB", "WR", "TE"],
    }
    scoring = existing.get("scoring") or {
        "reception": 0.5, "pass_yard": 0.04, "rush_yard": 0.1,
        "rec_yard": 0.1, "return_yard": 0.04, "touchdown": 6.0,
    }
    analysis = existing.get("analysis") or {
        "playoff_start_week": 15, "early_draft_rounds": 5,
    }

    def dump(table: str, d: dict) -> str:
        out = [f"[{table}]"]
        for k, v in d.items():
            if isinstance(v, str):
                out.append(f'{k} = "{v}"')
            elif isinstance(v, bool):
                out.append(f"{k} = {str(v).lower()}")
            elif isinstance(v, list):
                out.append(f"{k} = [" + ", ".join(f'"{x}"' for x in v) + "]")
            else:
                out.append(f"{k} = {v}")
        return "\n".join(out)

    path.write_text("\n\n".join([
        "# Generated by `fantasyedge setup`. Safe to hand-edit.",
        dump("league", league), dump("roster", roster),
        dump("scoring", scoring), dump("analysis", analysis),
    ]) + "\n")
    emit(args, {"wrote": str(path), "league": league}, f"Wrote {path}")


