DEFAULT_CONFIG = pathlib.Path("config/league.toml")


def load_config(path: pathlib.Path = DEFAULT_CONFIG) -> dict:
    if not path.exists():
        return {}
    with path.open("rb") as fh:
        return tomllib.load(fh)


def parse_seasons(spec: str) -> list[int]:
    """Accepts 2024, 2022-2026, or 2022,2024,2026."""
    out: set[int] = set()
    for chunk in spec.split(","):
        chunk = chunk.strip()
        if "-" in chunk:
            a, b = chunk.split("-", 1)
            out.update(range(int(a), int(b) + 1))
        elif chunk:
            out.add(int(chunk))
    return sorted(out)


def emit(args, payload: dict, human: str) -> None:
    """One output path, two renderings. Agents read JSON, humans read prose."""
    if getattr(args, "json", False):
        print(json.dumps(payload, indent=2))
    else:
        print(human)


def _scope(store: Store, cfg: dict, args) -> tuple[str, str]:
    provider = getattr(args, "provider", None) or cfg.get("league", {}).get("provider")
    league = getattr(args, "league", None) or cfg.get("league", {}).get("league_id")
    if not (provider and league):
        rows = store.seasons()
        if not rows:
            sys.exit("Nothing loaded yet. Run `pull` first.")
        provider, league = rows[0]["provider"], rows[0]["league_id"]
    return str(provider), str(league)


