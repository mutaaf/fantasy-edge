def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="fantasyedge", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--db", default="data/fantasy.db")
    p.add_argument("--config", default=str(DEFAULT_CONFIG))
    p.add_argument("--json", action="store_true",
                   help="machine-readable output for agents and scripts")
    sub = p.add_subparsers(dest="cmd", required=True)

    def jsonify(sp):
        """--json must work before OR after the subcommand.

        Argparse normally forces global flags to precede the subcommand, which
        is precisely the mistake an agent makes first. SUPPRESS means the
        subparser only sets the attribute when the flag is actually present,
        so the global value survives when it is not.
        """
        sp.add_argument("--json", action="store_true", default=argparse.SUPPRESS,
                        help="machine-readable output")
        return sp

    def common(sp):
        sp.add_argument("--provider", choices=pbase.known_providers())
        sp.add_argument("--league")
        return jsonify(sp)

    su = sub.add_parser("setup", help="write config/league.toml from flags")
    su.add_argument("--provider", default="espn", choices=pbase.known_providers())
    su.add_argument("--league"); su.add_argument("--teams", type=int)
    jsonify(su); su.set_defaults(fn=cmd_setup)

    dr = sub.add_parser("doctor", help="diagnose setup and print the next command")
    jsonify(dr); dr.set_defaults(fn=cmd_doctor)

    a = sub.add_parser("auth", help="one-time OAuth for Yahoo")
    a.add_argument("--provider", default="yahoo", choices=pbase.known_providers())
    a.add_argument("--url", action="store_true", help="print authorize URL and exit")
    a.add_argument("--code", help="authorization code, completes the exchange")
    a.add_argument("--local", action="store_true",
                   help="open a browser and catch the code on 127.0.0.1 "
                        "(needs a loopback redirect URI registered with the provider)")
    jsonify(a); a.set_defaults(fn=cmd_auth)

    d = common(sub.add_parser("discover", help="list leagues and seasons"))
    d.add_argument("--draft"); d.add_argument("--standings")
    d.set_defaults(fn=cmd_discover)

    pl = common(sub.add_parser("pull", help="ingest league-seasons"))
    pl.add_argument("--seasons", help="2024, 2022-2026, or 2022,2024")
    pl.add_argument("--season", type=int)
    pl.add_argument("--draft"); pl.add_argument("--standings")
    pl.add_argument("--teams", type=int)
    pl.set_defaults(fn=cmd_pull)

    ad = sub.add_parser("adp-load", help="load ADP for the reach analysis")
